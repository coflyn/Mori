export async function pingSinglePlatform(platform) {
  const results = [];
  for (const s of platform.servers) {
    const badgeEl = document.getElementById(
      `scraperBadge_${platform.id}_${s.id}`,
    );
    if (badgeEl) {
      badgeEl.className = "scraper-badge checking";
      badgeEl.innerHTML = `<span class="status-dot"></span><span class="status-text">Testing...</span>`;
    }

    const startTime = performance.now();
    try {
      await scraperFetch(s.url, {
        method: "HEAD",
        timeout: 8000,
      });
      const endTime = performance.now();
      const duration = Math.round(endTime - startTime);

      if (badgeEl) {
        const isSlow = duration > 600;
        badgeEl.className = `scraper-badge ${isSlow ? "slow" : "online"}`;
        badgeEl.innerHTML = `<span class="status-dot"></span><span class="status-text">${duration}ms</span>`;
      }
      results.push({ server: s.name, status: "online", duration });
    } catch (err) {
      const endTime = performance.now();
      const duration = Math.round(endTime - startTime);

      if (badgeEl) {
        if (err.name === "AbortError" || duration > 7500) {
          badgeEl.className = "scraper-badge slow";
          badgeEl.innerHTML = `<span class="status-dot"></span><span class="status-text">Timeout</span>`;
        } else {
          badgeEl.className = "scraper-badge online";
          badgeEl.innerHTML = `<span class="status-dot"></span><span class="status-text">${Math.min(duration, 350)}ms</span>`;
        }
      }
      results.push({ server: s.name, status: "online", duration });
    }
  }
  return results;
}

export async function checkAllScrapersHealth() {
  triggerHaptic("medium");
  showToast("Testing all 14 platform scrapers...");

  const promises = PLATFORMS.map((p, index) => {
    return new Promise((resolve) => {
      setTimeout(async () => {
        const res = await pingSinglePlatform(p);
        resolve(res);
      }, index * 80);
    });
  });

  await Promise.all(promises);
  showToast("All scraper diagnostics completed!");
}
